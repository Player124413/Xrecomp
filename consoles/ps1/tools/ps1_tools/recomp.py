"""`python3 -m ps1_tools.recomp INPUT OUTDIR [--discovered FILE]`: a PS1 program to C sources (XBA-160 / XBA-161).

INPUT is a PS-X EXE or a disc image (.cue / .bin / .iso: the EXE that SYSTEM.CNF boots). Writes
OUTDIR/ps1_rc_AAAAAAAA[_HHHHHHHH].c (the lifted functions, each file named after its first one: chunk_file) and
OUTDIR/ps1_rc_table.c (the table, exported as ps1_recomp_title_table), nothing else:
compile every .c of OUTDIR with -I consoles/ps1/runtime into one shared library (consoles/ps1/runtime/ps1_recomp.h
is the contract). Stale ps1_rc_*.c files of an earlier run are removed. Prints a JSON summary on stdout; --report
FILE writes it there too.

--discovered FILE: the runtime's record of code the interpreter had to run (ps1_recomp.h: `ADDR HASH HEXBYTES` per
line, or `ADDR` alone for code of the EXE). Code whose bytes match the EXE becomes a function of the EXE; any other
code (overlays loaded at run time, code copied or patched in RAM) is lifted from the recorded bytes, as functions
keyed by address and hash, so overlays sharing an address coexist in one pack. An address recorded with 8
(PS1_RECOMP_VARIANTS) different contents is code generated at run time: it stays interpreted. Records of one address
that agree over their common length are the same code (an older runtime recorded it again under another length):
they are merged, the longest kept, and only contents that differ inside their common length count as different.
"""

import argparse
import glob
import json
import os
import sys

from .discover import Discovery, Function, Image, merge_records
from .exe import load_input
from .lift import FnLifter, hx

VARIANTS = 8  # PS1_RECOMP_VARIANTS: an address recorded with this many contents is generated code, not lifted
# C files: functions in address order, cut so that a file's content and name stay the same when the discovery loop
# adds or splits functions elsewhere (Prepare's object cache then compiles only the files that changed). A file ends
# after a function whose identity (start, hash) hashes to 0 mod CHUNK_HASH once it holds CHUNK_MIN instructions, or at
# CHUNK_MAX. Files compile in parallel.
CHUNK_MIN = 1000
CHUNK_HASH = 8
CHUNK_MAX = 4000

HEADER = """/* Generated by ps1_tools.recomp (consoles/ps1/tools) from a PS1 program -- do not edit.
 * %s sha256 %s */
#include "ps1_recomp_rt.h"
"""


def read_discovered(path):
    """[(addr, bytes or None)] from a discovered file."""
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.split("#", 1)[0].split()
            if not s:
                continue
            try:
                addr = int(s[0], 16) & 0xFFFFFFFF
                data = bytes.fromhex(s[2]) if len(s) >= 3 else None
            except ValueError:
                continue
            if addr & 3:
                continue
            out.append((addr, data))
    return out


def fn_name(f):
    if f.name:
        base = f.name
    else:
        base = "f_%08X" % f.start
    if f.image.origin != "exe":
        base += "_%08x" % (f.hash & 0xFFFFFFFF)
    return "ps1_rc_" + base


def merge_variants(discovered):
    """{addr: [contents]} of the records with bytes: records of an address that agree over their common length are
    one content (the longest kept); the others are its variants."""
    out = {}
    for addr, data in discovered:
        if not data:
            continue
        reps = out.setdefault(addr, [])
        for k, r in enumerate(reps):
            n = min(len(r), len(data))
            if r[:n] == data[:n]:
                if len(data) > len(r):
                    reps[k] = data
                break
        else:
            reps.append(data)
    return out


def build_functions(exe, discovered):
    """Discovery over the EXE and the recorded RAM code. Returns (functions, stats)."""
    img = Image(exe.text_addr, exe.text, "exe")
    exe_seeds = {exe.pc0}
    records = []
    variants = merge_variants(discovered)
    volatile = {a for a, v in variants.items() if len(v) >= VARIANTS}
    for addr, data in discovered:
        if data is None:
            exe_seeds.add(addr)
    for addr in sorted(variants):
        if addr not in volatile:
            records += [(addr, data) for data in variants[addr]]
    # recorded code: functions found in the recorded bytes; the ones identical to the EXE go to the EXE
    ram_funcs = {}
    stats = {"records": len(records), "blobs": 0, "ram_functions": 0, "exe_seeds_from_records": 0,
             "volatile_addresses": len(volatile)}
    for base, data, seeds in merge_records(records):
        blob = Image(base, data, "ram")
        stats["blobs"] += 1
        for f in Discovery(blob, seeds).run():
            same = img.contains(f.start) and f.end <= img.end and img.words(f.start, f.end) == blob.words(f.start, f.end)
            if same:
                if f.start not in exe_seeds:
                    stats["exe_seeds_from_records"] += 1
                exe_seeds.add(f.start)
                continue
            key = (f.start, f.end, f.hash)
            if key not in ram_funcs:
                ram_funcs[key] = f
    disc = Discovery(img, exe_seeds)
    funcs = disc.run()
    stats.update({"exe_" + k: v for k, v in disc.stats.items()})
    stats["ram_functions"] = len(ram_funcs)
    funcs += sorted(ram_funcs.values(), key=lambda f: (f.start, f.hash))
    return funcs, stats


def chunk_cut(f):
    """A stable pseudo-random hash of a function's identity (the same on every run and host)."""
    return (((f.start ^ (f.hash & 0xFFFFFFFF)) * 2654435761) >> 7) % CHUNK_HASH == 0


def chunks_of(funcs):
    """The functions grouped into files (see CHUNK_MIN)."""
    chunks, cur, n = [], [], 0
    for f in sorted(funcs, key=lambda f: (f.start, f.image.origin != "exe", f.hash)):
        cur.append(f)
        n += (f.end - f.start) // 4
        if n >= CHUNK_MAX or (n >= CHUNK_MIN and chunk_cut(f)):
            chunks.append(cur)
            cur, n = [], 0
    if cur:
        chunks.append(cur)
    return chunks


def chunk_file(f):
    """A file's name, after its first function: ps1_rc_AAAAAAAA.c (the EXE's), ps1_rc_AAAAAAAA_HHHHHHHH.c (code
    recorded in RAM: address and hash)."""
    if f.image.origin == "exe":
        return "ps1_rc_%08X.c" % f.start
    return "ps1_rc_%08X_%08x.c" % (f.start, f.hash & 0xFFFFFFFF)


def recompile(exe, outdir, discovered=(), comments=True, resume_all=False):
    funcs, stats = build_functions(exe, list(discovered))
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "ps1_rc_*.c")):
        os.remove(old)
    names = {}
    for f in funcs:
        n = fn_name(f)
        while n in names.values():
            n += "_"
        names[id(f)] = n
    files, fallbacks, insns = [], 0, 0
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, chunk_file(chunk[0]))
        parts = [HEADER % (exe.name, exe.sha256)]
        for f in chunk:
            lifter = FnLifter(f, names[id(f)], resume_all=resume_all)
            parts.append("\n" + lifter.function(comments))
            fallbacks += lifter.fallbacks
            insns += (f.end - f.start) // 4
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = sorted(funcs, key=lambda f: (f.start, f.hash))
    tab = [HEADER % (exe.name, exe.sha256), "\n"]
    for f in entries:
        tab.append("RC_FN %s(ps1_machine *m_);\n" % names[id(f)])
    tab.append("\nstatic const ps1_recomp_entry entries[] = {\n")
    for f in entries:
        tab.append("    {%s, %du, 0x%016XULL, %s},\n" % (hx(f.start), f.end - f.start, f.hash, names[id(f)]))
    if not entries:
        tab.append("    {0, 0, 0, 0},\n")
    tab.append("};\n\nstatic const ps1_recomp_table table = {PS1_RECOMP_ABI, %du, entries, \"%s\", %s};\n\n"
               % (len(entries), exe.sha256, hx(exe.pc0)))
    tab.append("RC_EXPORT const ps1_recomp_table *ps1_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "ps1_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    stats.update({
        "exe": exe.as_dict(),
        "functions": len(funcs),
        "bios_stubs": sum(1 for f in funcs if f.kind == "bios_stub"),
        "instructions": insns,
        "table_entries": len(entries),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(list(discovered)),
        "files": [os.path.basename(p) for p in files],
    })
    return stats


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ps1_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("input", help="PS-X EXE or disc image (.cue / .bin / .iso)")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="the runtime's record of code it had to interpret (ps1_recomp.h)")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    ap.add_argument("--resume-all", action="store_true",
                    help="debugging: every instruction a block of its own (a resume point with its own event check; "
                         "much slower to compile)")
    args = ap.parse_args(argv)
    try:
        exe = load_input(args.input)
    except (OSError, ValueError) as e:
        print("ps1_tools.recomp: %s: %s" % (args.input, e), file=sys.stderr)
        return 2
    summary = recompile(exe, args.outdir, read_discovered(args.discovered), not args.no_comments, args.resume_all)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
