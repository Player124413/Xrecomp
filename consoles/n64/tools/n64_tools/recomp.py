"""`python3 -m n64_tools.recomp ROM OUTDIR [--discovered FILE]`: an N64 ROM to C sources (XBA-169 / XBA-170).

ROM in any byte order (.z64 / .v64 / .n64), nothing else: no symbol or ELF file, no per-title configuration. Writes
OUTDIR/n64_rc_AAAAAAAA[_HHHHHHHH].c (the lifted functions, files named after their first function) and OUTDIR/n64_rc_table.c (the table, exported as n64_recomp_title_table),
nothing else: compile every .c of OUTDIR with -I consoles/n64/runtime into one shared library
(consoles/n64/runtime/n64_recomp.h is the contract). Stale n64_rc_*.c files of an earlier run are removed. Prints a
JSON summary on stdout; --report FILE writes it there too.

--discovered FILE: the runtime's record of code the interpreter had to run (n64_recomp.h: `ADDR HASH HEXBYTES` per
line, or `ADDR` alone for code of the ROM's static images). Code whose bytes match a static image becomes a function
of that image; any other code (overlays loaded at run time, decompressed or TLB-mapped code) is lifted from the
recorded bytes, as functions keyed by address and hash, so overlays sharing an address coexist in one pack. An address
recorded with 8 (N64_RECOMP_VARIANTS) different contents is code generated at run time: it stays interpreted.
Records of one address that agree over their common length are the same code recorded from further or less far (a
runtime before 2026-11-15 recorded the same code again under another length): they are merged, the longest kept, and
only contents that differ inside their common length count as different.
"""

import argparse
import glob
import json
import os
import sys

from .discover import VECTORS, Discovery, Image, merge_records
from .dma import find_segments
from .lift import FnLifter, hx
from .rom import load_rom

VARIANTS = 8  # N64_RECOMP_VARIANTS
# Files: functions in address order, a file cut after a function whose identity (start, hash) hashes to 0 mod
# CHUNK_HASH once it holds CHUNK_MIN instructions, or at CHUNK_MAX. Names and contents stay the same from one discovery
# round to the next except where functions were added, so a round recompiles about one file per new function (the
# object cache of tools/consoles/n64_recomp_build.py and Prepare). Files compile in parallel.
CHUNK_MIN = 1000
CHUNK_HASH = 8
CHUNK_MAX = 4000

HEADER = """/* Generated by n64_tools.recomp (consoles/n64/tools) from an N64 ROM -- do not edit.
 * %s sha256 %s */
#include "n64_recomp_rt.h"
"""


def read_discovered(path):
    """[(addr, bytes or None)] from a discovered file."""
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.split("#", 1)[0].split()
            if not s:
                continue
            try:
                addr = int(s[0], 16) & 0xFFFFFFFF
                data = bytes.fromhex(s[2]) if len(s) >= 3 else None
            except ValueError:
                continue
            if addr & 3:
                continue
            out.append((addr, data))
    return out


def merge_variants(discovered):
    """{addr: [contents]} of the records with bytes: records of an address that agree over their common length are
    one content (the longest kept); the others are its variants."""
    out = {}
    for addr, blob in discovered:
        if blob is None or not blob:
            continue
        reps = out.setdefault(addr, [])
        for k, r in enumerate(reps):
            n = min(len(r), len(blob))
            if r[:n] == blob[:n]:
                if len(blob) > len(r):
                    reps[k] = blob
                break
        else:
            reps.append(blob)
    return out


def static_images(rom):
    """The images of the ROM's boot (rom.py) and of the PI DMA copies found statically (dma.py)."""
    imgs = [Image(s.vaddr, s.data, s.origin, s.executable) for s in rom.segments]
    code = [im for im in imgs if im.executable]
    dma = find_segments(rom, code)
    return imgs, code, dma


def build_functions(rom, discovered):
    """Discovery over the ROM's images and the recorded RDRAM code. Returns (functions, stats)."""
    imgs, code, dma = static_images(rom)
    code = code + dma
    data = imgs + dma
    seeds = {rom.entry} | set(VECTORS)
    records = []
    variants = merge_variants(discovered)
    volatile = {a for a, v in variants.items() if len(v) >= VARIANTS}
    for addr, blob in discovered:
        if blob is None:
            seeds.add(addr)
    for addr in sorted(variants):
        if addr not in volatile:
            records += [(addr, blob) for blob in variants[addr]]
    stats = {"records": len(records), "blobs": 0, "ram_functions": 0, "seeds_from_records": 0,
             "volatile_addresses": len(volatile), "dma_segments": [hx(d.base) + "+0x%X" % len(d.data) for d in dma],
             "images": [{"base": hx(im.base), "size": len(im.data), "origin": im.origin} for im in code]}
    # recorded code: functions found in the recorded bytes; the ones identical to a static image go to that image
    ram_funcs = {}
    for base, blob, rseeds in merge_records(records):
        bimg = Image(base, blob, "ram")
        stats["blobs"] += 1
        for f in Discovery(bimg, rseeds, sweep=False).run():
            home = next((im for im in code if im.contains(f.start) and f.end <= im.end), None)
            if home is not None and home.words(f.start, f.end) == bimg.words(f.start, f.end):
                if f.start not in seeds:
                    stats["seeds_from_records"] += 1
                seeds.add(f.start)
                continue
            key = (f.start, f.end, f.hash)
            if key not in ram_funcs:
                ram_funcs[key] = f
    funcs = []
    for im in code:
        disc = Discovery(im, seeds, data_images=data)
        funcs += disc.run()
        for k, v in disc.stats.items():
            stats["static_" + k] = stats.get("static_" + k, 0) + v
    stats["ram_functions"] = len(ram_funcs)
    funcs += sorted(ram_funcs.values(), key=lambda f: (f.start, f.hash))
    return funcs, stats


def fn_name(f):
    base = "n64_rc_f_%08X" % f.start
    if f.image.origin in ("ram", "dma"):
        base += "_%08x" % (f.hash & 0xFFFFFFFF)
    return base


def chunk_cut(f):
    """A stable pseudo-random hash of a function's identity (the same on every run and host)."""
    return (((f.start ^ (f.hash & 0xFFFFFFFF)) * 2654435761) >> 7) % CHUNK_HASH == 0


def chunks_of(funcs):
    """The functions grouped into files (see CHUNK_MIN)."""
    chunks, cur, n = [], [], 0
    for f in sorted(funcs, key=lambda f: (f.start, f.image.origin in ("ram", "dma"), f.hash)):
        cur.append(f)
        n += (f.end - f.start) // 4
        if n >= CHUNK_MAX or (n >= CHUNK_MIN and chunk_cut(f)):
            chunks.append(cur)
            cur, n = [], 0
    if cur:
        chunks.append(cur)
    return chunks


def chunk_file(f):
    """A file's name, after its first function: n64_rc_AAAAAAAA.c (a static image's), n64_rc_AAAAAAAA_HHHHHHHH.c
    (recorded or DMA code: address and hash)."""
    if f.image.origin in ("ram", "dma"):
        return "n64_rc_%08X_%08x.c" % (f.start, f.hash & 0xFFFFFFFF)
    return "n64_rc_%08X.c" % f.start


def recompile(rom, outdir, discovered=(), comments=True, resume_all=False):
    funcs, stats = build_functions(rom, list(discovered))
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "n64_rc_*.c")):
        os.remove(old)
    names, used = {}, set()
    for f in funcs:
        n = fn_name(f)
        while n in used:
            n += "_"
        used.add(n)
        names[id(f)] = n
    files, fallbacks, insns = [], 0, 0
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, chunk_file(chunk[0]))
        parts = [HEADER % (rom.name, rom.sha256)]
        for f in chunk:
            lifter = FnLifter(f, names[id(f)], resume_all=resume_all)
            parts.append("\n" + lifter.function(comments))
            fallbacks += lifter.fallbacks
            insns += (f.end - f.start) // 4
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = sorted(funcs, key=lambda f: (f.start, f.hash))
    tab = [HEADER % (rom.name, rom.sha256), "\n"]
    for f in entries:
        tab.append("RC_FN %s(n64_machine *m_);\n" % names[id(f)])
    tab.append("\nstatic const n64_recomp_entry entries[] = {\n")
    for f in entries:
        tab.append("    {%s, %du, 0x%016XULL, %s},\n" % (hx(f.start), f.end - f.start, f.hash, names[id(f)]))
    if not entries:
        tab.append("    {0, 0, 0, 0},\n")
    tab.append("};\n\nstatic const n64_recomp_table table = {N64_RECOMP_ABI, %du, entries, \"%s\", %s};\n\n"
               % (len(entries), rom.sha256, hx(rom.entry)))
    tab.append("RC_EXPORT const n64_recomp_table *n64_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "n64_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    stats.update({
        "rom": rom.as_dict(),
        "functions": len(funcs),
        "instructions": insns,
        "table_entries": len(entries),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(list(discovered)),
        "files": [os.path.basename(p) for p in files],
    })
    return stats


def main(argv=None):
    ap = argparse.ArgumentParser(prog="n64_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("rom", help="N64 ROM (.z64 / .v64 / .n64, any byte order)")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="the runtime's record of code it had to interpret (n64_recomp.h)")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    ap.add_argument("--resume-all", action="store_true",
                    help="every instruction a block of its own (debugging: an event check before each)")
    args = ap.parse_args(argv)
    try:
        rom = load_rom(args.rom)
    except (OSError, ValueError) as e:
        print("n64_tools.recomp: %s: %s" % (args.rom, e), file=sys.stderr)
        return 2
    summary = recompile(rom, args.outdir, read_discovered(args.discovered), not args.no_comments, args.resume_all)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
